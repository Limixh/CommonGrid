import { readFile, writeFile, mkdir } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const schemaText = await readFile(
  new URL("packages/task-schema/schema/contracts.schema.json", root),
  "utf8",
);
const schema = JSON.parse(schemaText);
const check = process.argv.includes("--check");
async function emit(relative, content) {
  const url = new URL(relative, root);
  if (check) {
    const existing = await readFile(url, "utf8").catch(() => "");
    if (existing !== content)
      throw new Error(
        `Generated file is stale: ${relative}. Run npm run generate.`,
      );
  } else {
    await mkdir(new URL("./", url), { recursive: true });
    await writeFile(url, content);
  }
}
await emit(
  "packages/task-schema/src/generated.ts",
  await compile(schema, schema.title, {
    bannerComment: "/* Generated by npm run generate. Do not edit. */",
    style: { singleQuote: true },
    unreachableDefinitions: true,
    ignoreMinAndMaxItems: true,
  }),
);
const pascal = (name) =>
  name
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
function goType(node) {
  if (node.$ref) return node.$ref.split("/").at(-1);
  if (node.type === "string") return "string";
  if (node.type === "integer") return "int64";
  if (node.type === "number") return "float64";
  if (node.type === "boolean") return "bool";
  if (node.type === "array") return "[]" + goType(node.items);
  throw new Error(
    "Go generator needs an explicit supported type: " + JSON.stringify(node),
  );
}
let go =
  "// Code generated by npm run generate; DO NOT EDIT.\npackage contract\n\n";
for (const [name, node] of Object.entries(schema.$defs)) {
  if (node.type !== "object") {
    go += `type ${name} = ${goType(node)}\n\n`;
    continue;
  }
  go += `type ${name} struct {\n`;
  for (const [field, property] of Object.entries(node.properties)) {
    const optional = !node.required?.includes(field);
    go += `\t${pascal(field)} ${optional ? "*" : ""}${goType(property)} \x60json:"${field}${optional ? ",omitempty" : ""}"\x60\n`;
  }
  go += "}\n\n";
}
go += `var immutableFields = []string{${Object.keys(
  schema.$defs.TaskContract.properties,
)
  .filter((k) => k !== "contract_hash")
  .map((k) => JSON.stringify(k))
  .join(", ")}}\n`;
await emit("services/coordinator/internal/contract/types_generated.go", go);
await emit(
  "services/coordinator/internal/contract/contracts.schema.json",
  schemaText,
);
await emit(
  "services/coordinator/internal/catalog/catalog.json",
  await readFile(
    new URL("packages/task-schema/fixtures/catalog.json", root),
    "utf8",
  ),
);
console.log(
  check
    ? "Generated contracts are current."
    : "TypeScript / Go contracts generated.",
);
