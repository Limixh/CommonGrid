import { readFile, writeFile, mkdir } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { fileURLToPath } from "node:url";
import { loadSoftwareBundle } from "./software-bundle.mjs";
const root = new URL("../", import.meta.url);
const schemaText = await readFile(
  new URL("packages/task-schema/schema/contracts.schema.json", root),
  "utf8",
);
const schema = JSON.parse(schemaText);
const check = process.argv.includes("--check");
async function emit(relative, content) {
  const url = new URL(relative, root);
  if (check) {
    const existing = await readFile(url, "utf8").catch(() => "");
    if (existing !== content)
      throw new Error(
        `Generated file is stale: ${relative}. Run npm run generate.`,
      );
  } else {
    await mkdir(new URL("./", url), { recursive: true });
    await writeFile(url, content);
  }
}
await emit(
  "packages/task-schema/src/generated.ts",
  await compile(schema, schema.title, {
    bannerComment: "/* Generated by npm run generate. Do not edit. */",
    style: { singleQuote: true },
    unreachableDefinitions: true,
    ignoreMinAndMaxItems: true,
  }),
);
// Compile once at build time: native CSP forbids Ajv's runtime Function constructor.
const validatorNames = ["TaskContract", "ExecutionContext", "Checkpoint", "PlannerProposal"];
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, esm: true, lines: true } });
ajv.addSchema(schema);
let validators = standaloneCode(ajv, Object.fromEntries(
  validatorNames.map(name => [name, `${schema.$id}#/$defs/${name}`]),
));
// Ajv's ESM standalone output still uses require for runtime helpers. Keep its
// own helper implementations, but import them in a form Node and Vite can use.
validators = validators.replace(/const (\w+) = require\("(ajv\/dist\/runtime\/\w+)"\)\.default;/g,
  (_match, binding, module) => `import ${binding}Module from "${module}.js";\nconst ${binding} = typeof ${binding}Module === "function" ? ${binding}Module : ${binding}Module.default;`);
if (/\brequire\s*\(/.test(validators)) throw new Error("Unsupported standalone validator runtime import");
await emit("packages/task-schema/src/validators.generated.js",
  "/* Generated by npm run generate. Do not edit. */\n" + validators.trimEnd() + "\n");
await emit("packages/task-schema/src/validators.generated.d.ts",
  "/* Generated by npm run generate. Do not edit. */\n" +
  'import type { ValidateFunction } from "ajv";\nimport type * as Contract from "./generated";\n' +
  validatorNames.map(name => `export declare const ${name}: ValidateFunction<Contract.${name}>;\n`).join(""));
const pascal = (name) =>
  name
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
function goType(node) {
  if (node.$ref) return node.$ref.split("/").at(-1);
  if (node.type === "string") return "string";
  if (node.type === "integer") return "int64";
  if (node.type === "number") return "float64";
  if (node.type === "boolean") return "bool";
  if (node.type === "array") return "[]" + goType(node.items);
  throw new Error(
    "Go generator needs an explicit supported type: " + JSON.stringify(node),
  );
}
let go =
  "// Code generated by npm run generate; DO NOT EDIT.\npackage contract\n\n";
for (const [name, node] of Object.entries(schema.$defs)) {
  if (node.type !== "object") {
    go += `type ${name} = ${goType(node)}\n\n`;
    continue;
  }
  go += `type ${name} struct {\n`;
  for (const [field, property] of Object.entries(node.properties)) {
    const optional = !node.required?.includes(field);
    go += `\t${pascal(field)} ${optional ? "*" : ""}${goType(property)} \x60json:"${field}${optional ? ",omitempty" : ""}"\x60\n`;
  }
  go += "}\n\n";
}
go += `var immutableFields = []string{${Object.keys(
  schema.$defs.TaskContract.properties,
)
  .filter((k) => k !== "contract_hash")
  .map((k) => JSON.stringify(k))
  .join(", ")}}\n`;
await emit("services/coordinator/internal/contract/types_generated.go", go);
await emit(
  "services/coordinator/internal/contract/contracts.schema.json",
  schemaText,
);
await emit(
  "services/coordinator/internal/catalog/catalog.json",
  await readFile(
    new URL("packages/task-schema/fixtures/catalog.json", root),
    "utf8",
  ),
);
// Pinned local software bundles: file contents, hashes and the synthetic git
// ids that each catalog contract's workspace.commit refers to.
for (const [taskId, exportName] of [["software-bounds", "softwareBoundsBundle"], ["software-intervals", "softwareIntervalsBundle"]]) {
  const bundle = await loadSoftwareBundle(taskId);
  await emit(
    `packages/agent-adapters/src/${taskId}-bundle.generated.ts`,
    "/* Generated by npm run generate. Do not edit. */\n" +
      `export const ${exportName} = ` +
      JSON.stringify({
        files: bundle.files,
        git: { commit: bundle.ids.commit, tree: bundle.ids.tree, trees: bundle.ids.trees, blobs: bundle.ids.blobs },
      }, null, 2) +
      " as const;\n",
  );
}
console.log(
  check
    ? "Generated contracts are current."
    : "TypeScript / Go contracts generated.",
);
